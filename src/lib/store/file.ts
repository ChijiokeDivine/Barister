/**
 * Local-dev driver: one JSON file + a blobs directory under ./.data.
 * Reads from disk on EVERY call (no in-memory cache) because Next dev can instantiate this module once per
 * route bundle — a cache would silently diverge between routes. Writes are serialised and atomic (tmp+rename).
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import type { Blobs, KV, Store } from "./types";

interface Db {
  c: Record<string, Record<string, string>>; // collections: name → id → JSON
  h: Record<string, Record<string, string>>; // hashes
  l: Record<string, string[]>; // lists
}

const ROOT = path.join(process.cwd(), ".data");
const DB_FILE = path.join(ROOT, "kv.json");
const BLOB_DIR = path.join(ROOT, "blobs");

// Single process-wide mutex shared across duplicated module instances.
const g = globalThis as unknown as { __lfLock?: Promise<unknown> };
function locked<T>(fn: () => Promise<T>): Promise<T> {
  const run = (g.__lfLock ?? Promise.resolve()).then(fn, fn);
  g.__lfLock = run.catch(() => undefined);
  return run;
}

async function load(): Promise<Db> {
  try {
    return JSON.parse(await fs.readFile(DB_FILE, "utf8")) as Db;
  } catch {
    return { c: {}, h: {}, l: {} };
  }
}

async function save(db: Db) {
  await fs.mkdir(ROOT, { recursive: true });
  const tmp = `${DB_FILE}.${process.pid}.tmp`;
  await fs.writeFile(tmp, JSON.stringify(db));
  await fs.rename(tmp, DB_FILE);
}

const mutate = <T>(fn: (db: Db) => T) =>
  locked(async () => {
    const db = await load();
    const out = fn(db);
    await save(db);
    return out;
  });

const kv: KV = {
  async get<T>(col: string, id: string) {
    const raw = (await load()).c[col]?.[id];
    return raw ? (JSON.parse(raw) as T) : null;
  },
  put: (col, id, value) => mutate((db) => void ((db.c[col] ??= {})[id] = JSON.stringify(value))),
  del: (col, id) => mutate((db) => void delete db.c[col]?.[id]),
  async list<T>(col: string) {
    return Object.values((await load()).c[col] ?? {}).map((s) => JSON.parse(s) as T);
  },
  hset: (key, fields) => mutate((db) => void Object.assign((db.h[key] ??= {}), fields)),
  async hgetall(key) {
    return { ...((await load()).h[key] ?? {}) };
  },
  delKey: (key) => mutate((db) => void (delete db.h[key], delete db.l[key])),
  rpush: (key, values) => mutate((db) => void (db.l[key] ??= []).push(...values)),
  async lrange(key, start, end = -1) {
    const list = (await load()).l[key] ?? [];
    return list.slice(start, end === -1 ? undefined : end + 1);
  },
};

// Keys are generated by us (ids/prefixes), but sanitise anyway so a crafted key can never escape the blob dir.
const blobPath = (key: string) => path.join(BLOB_DIR, key.replace(/[^a-zA-Z0-9/_.-]/g, "_").replace(/\.\.+/g, "_"));

const blobs: Blobs = {
  async put(key, data) {
    const p = blobPath(key);
    await fs.mkdir(path.dirname(p), { recursive: true });
    await fs.writeFile(p, data);
  },
  async get(key) {
    return fs.readFile(blobPath(key)).catch(() => null);
  },
  async del(key) {
    await fs.rm(blobPath(key), { force: true });
  },
};

export const fileStore = (): Store => ({ kv, blobs, driver: "file" });
